import * as THREE from 'three';
import fs from 'fs';
import { createAnatomy } from './anatomy3.js';
import { makePhysics } from './physics_core.mjs';
import { CUE_TONE } from './physics_params.mjs';
const A = createAnatomy(THREE);
const PH = makePhysics(A, { mass: 70 });
const data = JSON.parse(fs.readFileSync('poses.json', 'utf8'));
const id = process.argv[2] || 'bow';
const cone = process.argv[3] ? +process.argv[3] : 1;
const conf = A.poseFromData(data[id]); const W = A.placeW(conf.local, conf.rootQ);
const grips = ['L', 'R'].map(sd => { const l = A.LANDMARKS.find(x => x.tag === 'palm' && x.side === sd); return { hand: 'hand_' + sd, shank: 'shank_' + sd, P: A.pt(W, l.seg, l.p), side: sd, from: 'hum_' + sd, cone }; });
const r = PH.solve({ local: conf.local, rootQ: conf.rootQ }, { tone: CUE_TONE[id], grips, iters: 16000 });
const g = r.gripF.find(g => g.side === 'L');
const u = g.P.clone().sub(r.W.hum_L.p).normalize();
const perp = g.F.clone().addScaledVector(u, -g.F.dot(u));
console.log('arm dir', u.toArray().map(v => v.toFixed(2)).join(','), '| grip F', g.F.toArray().map(v => v.toFixed(1)).join(','), '| along', g.F.dot(u).toFixed(1), 'perp', perp.toArray().map(v => v.toFixed(1)).join(','), '|perp|', perp.length().toFixed(1));
let cost = 0; r.INST.forEach((s, j) => cost += r.FMAX[j] / 1000 * r.act[j] ** 2);
console.log('muscle cost', cost.toFixed(3));
const mus = {}; r.INST.forEach((s, j) => { if (s.side !== 'L') return; const m = (mus[s.unit] ||= { F: 0, Fmax: 0 }); m.F += r.force[j]; m.Fmax += r.FMAX[j]; });
console.log(Object.entries(mus).map(([u, m]) => [u, m.F / m.Fmax]).sort((a, b) => b[1] - a[1]).slice(0, 16).map(([u, a]) => u + ' ' + Math.round(a * 100)).join(', '));
const d = n => r.dofOut[PH.dofIndex[n]];
for (const n of ['gh_L_x', 'gh_L_y', 'gh_L_z', 'sc_L_x', 'sc_L_y', 'sc_L_z']) console.log(n, 'ext', d(n).ext.toFixed(1), 'st', d(n).st.toFixed(1), 'mus', d(n).mus.toFixed(1), 'pas', d(n).pas.toFixed(1));

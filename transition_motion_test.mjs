import assert from 'node:assert/strict';
import { A, X, qAx, blankLocal, setSide } from './cycle_lib.mjs';
import { createElbowMotionGuard } from './transition_motion.mjs';
const guard = createElbowMotionGuard(A), conf = { local: blankLocal() };
for (const side of ['L', 'R']) setSide(conf.local, side, 'fore', qAx(X, -20));
assert.equal(guard.inspect(conf).valid, true);
for (const value of Object.values(guard.inspect(conf).flexDeg)) assert(Math.abs(value - 20) < 1e-10);
for (const side of ['L', 'R']) setSide(conf.local, side, 'fore', qAx(X, 20));
assert.equal(guard.inspect(conf).valid, false, 'The former +20-degree open-arm quaternion is hyperextension, not flexion');
assert.equal(guard.inspect(conf).violations.length, 2);
for (const side of ['L', 'R']) setSide(conf.local, side, 'fore', qAx(X, 5));
assert.equal(guard.inspect(conf).valid, true, 'The existing model extension boundary stays unchanged');
setSide(conf.local, 'L', 'fore', qAx(X, 5.1));
assert.equal(guard.inspect(conf).valid, false, 'New hyperextension beyond the model range is rejected');
for (const side of ['L', 'R']) setSide(conf.local, side, 'fore', qAx(X, -150));
assert.equal(guard.inspect(conf).valid, true, 'The existing model flexion boundary stays unchanged');
setSide(conf.local, 'R', 'fore', qAx(X, -150.1));
assert.equal(guard.inspect(conf).valid, false, 'New flexion beyond the model range is rejected');
console.log('PASS elbow motion: normal flexion, former sign error, and model extension boundary.');
